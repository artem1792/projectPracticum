package main

import "fmt"

// Задача 1.2
// Поменять местами значение 2-х переменных
// - через третью переменную
// - без третьей переменной

func main() {
	// через третью переменную
	a := 5
	b := 10

	c := a
	a = b
	b = c

	fmt.Println(a, b)

	// без третьей переменной
	x := 7
	y := 3

	x = x + y
	y = x - y
	x = x - y

	fmt.Println(x, y)
}